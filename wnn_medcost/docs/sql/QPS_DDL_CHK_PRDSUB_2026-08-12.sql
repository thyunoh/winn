-- ═══════════════════════════════════════════════════════════════════════════
-- 점검표 엔진 — **기간 세분** `PRD_SUB` : 기간 칸 안의 하위 칸 (2026-08-12)
--
-- ★★이 파일은 **새 WAR 를 올리기 전에** 실행한다. (더하기만 하는 ALTER)
--
-- ★근거 8종 — ***등록이 처음으로 막힌 자리다.***
--   | 부서 | 서식 | 기간 안을 무엇으로 쪼개나 |
--   |---|---|---|
--   | 간호/병동 (7) | 물품 Count · 향정 비치 의약품 · 낙상예방활동 · 위해도구 일일 … | **D · E · N**(근무조) · 상·중·하 · 15일/30일 |
--   | 영양 (1) | 냉장고/냉동고/주방 온도·습도관리 기록지 | **10시 / 15시** |
--
--   ★★***값이 제각각이라 고정 목록으로는 안 된다.*** `D·E·N` 을 박아 넣으면 「10시·15시」가 안 되고,
--     둘 다 박으면 다음에 「오전·오후」가 나온다. ⇒ **서식이 이름을 정한다.**
--     `PRD_KIND` 가 「기간이 무엇인가」(일·요일·주차·월·분기)를 정했듯,
--     `PRD_SUB` 는 「그 기간 안을 몇으로 쪼개고 뭐라 부르나」를 정한다. ***짝이 되는 칸이다.***
--
-- ★값
--     PRD_SUB : 쉼표로 나열. 비면 지금처럼 한 칸. 예) `D,E,N` · `10시,15시` · `상,중,하`
--               ⚠**최대 9쪽** — 아래 번호 규칙 때문이다.
--
-- ★★번호 규칙 — **기간번호 × 10 + 쪽번호**
--     `1일 D` = 11 · `1일 E` = 12 · `31일 N` = 313 … / `월요일 10시` = 11 · `월요일 15시` = 12
--   · 기간이 **열**인 축(ITEM_DAY·ITEM_MONTH·EQUIP_DAY)은 `COL_NO` 가, 기간이 **행**인 축(DAY_ITEM)은
--     `ROW_NO` 가 이 번호를 쓴다. ***쪼개지는 쪽이 어디든 규칙은 하나다.***
--   · 최대 315 라 예약 번호와 겹치지 않는다 — 사인 900 · 앞뒤 열 1000/2000 · 묶음 1000 단위.
--
-- ⚠⚠***이미 자료가 쌓인 서식에 나중에 PRD_SUB 를 켜면 옛 값이 어긋난다.***
--   쪼개기 전 「11일」의 값과 쪼갠 뒤 「1일 E」의 값이 **같은 번호 11** 을 쓰기 때문이다.
--   ⇒ 켜는 것은 **자료가 없을 때**만. 이미 쓰던 서식이면 **새 서식으로 만든다.**
--     (서식 관리 화면이 이 경고를 띄운다)
--
-- ⚠기간 칸이 있는 축만 뜻이 있다 — `LIST`·`ITEM_COL` 은 격자에 기간이 없다.
-- ═══════════════════════════════════════════════════════════════════════════

ALTER TABLE TBL_QPS_CHK_FORM
  ADD COLUMN PRD_SUB VARCHAR(200) NULL
      COMMENT "기간 칸 안을 쪼개는 이름들(쉼표, 최대 9). 예 'D,E,N'. 번호=기간×10+쪽"
      AFTER PRD_KIND;

-- ── 확인 ────────────────────────────────────────────────────────────────────
SELECT COLUMN_NAME, COLUMN_TYPE, COLUMN_COMMENT FROM INFORMATION_SCHEMA.COLUMNS
 WHERE TABLE_SCHEMA='WNN' AND TABLE_NAME='TBL_QPS_CHK_FORM'
   AND COLUMN_NAME IN ('PRD_GB','PRD_KIND','PRD_SUB') ORDER BY ORDINAL_POSITION;
SELECT AXIS_GB, IFNULL(PRD_SUB,'-') AS PRD_SUB, COUNT(*) AS cnt
  FROM TBL_QPS_CHK_FORM GROUP BY AXIS_GB, PRD_SUB ORDER BY AXIS_GB;
-- ★이미 쌓인 값 중 번호 규칙과 부딪히는 것이 있는지(있으면 안 된다)
SELECT COUNT(*) AS 열번호_32에서_899 FROM TBL_QPS_CHK_VAL WHERE COL_NO BETWEEN 32 AND 899;
SELECT COUNT(*) AS 행번호_32에서_899 FROM TBL_QPS_CHK_VAL WHERE ROW_NO BETWEEN 32 AND 899;
