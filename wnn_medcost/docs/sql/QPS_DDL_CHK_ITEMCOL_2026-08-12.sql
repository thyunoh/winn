-- 점검표 엔진 v3 — `ITEM_COL` 축 (항목 행 × 날짜 아닌 고정 열) · 2026-08-12
--
-- ★★이 파일은 **새 WAR 를 올리기 전에** 실행한다.
--   새 코드의 서식 조회가 COL_NMS 를 읽으므로, 컬럼이 없으면
--   「Unknown column 'COL_NMS'」 로 **서식 화면이 통째로 죽는다.**
--   순서 : ① 이 SQL  ② WAR 교체  ③ 톰캣 재기동
--
-- ★왜 만드나 — ***네 부서 캡처에서 23종이 이 모양이다. 단일 최대다.***
--   지금 축 다섯은 **전부 날짜(또는 월)가 한 축**이거나 행이 자유(LIST)다.
--   그런데 「항목 행 × 날짜가 아닌 열」이 계속 나왔다 :
--
--   | 서식 | 고정 열 |
--   |---|---|
--   | 비치의약품 보관상태 점검대장 (약국·병동)  | Y · N · 비고 |
--   | 일일위생안전청소점검일지 (영양)           | 점검결과 · 조치사항 |
--   | 의료·유해물질 취급부서 월 안전점검일지 (시설) | 예 · 아니오 · 해당없음 |
--   | 발전기 운전 점검일지 (시설)               | 결과 · 비고 |
--   | 가스시설 점검표 (시설)                    | **점검 및 조치>점검결과 · 점검 및 조치>조치 사항** |
--   | 건축물 안전 점검 일지 (시설)              | **3월>일 · 6월>일 · 9월>일 · 12월>일** (분기) |
--   | 고위험 병실 순회 · 병동 순회일지 (병동)   | 유 · 무 · 점검자 / 점검내용 8열 |
--   | 정신과적 고위험 환자 명단표 (병동)        | 환자명 |
--   | 공기조화설비 3종 (시설)                   | 점검결과(O, X, 미해당) |
--   | … 그 밖 |
--
--   ***★열 이름만 다를 뿐 구조가 같다.*** 그래서 **열 이름을 서식이 정하게** 한다.
--   ⇒ 축 하나가 「날짜가 아닌 모든 열 구성」을 덮는다. 분기(4칸)도 여기 들어간다 —
--     ***분기 축을 따로 만들 필요가 없다.***
--
-- ★`COL_NMS` 문법 — 쉼표로 나열, 묶음은 `묶음>열`
--     Y,N,비고
--     예,아니오,해당없음
--     점검 및 조치>점검결과,점검 및 조치>조치 사항      ← 2단 열 머리글
--     3월>일,6월>일,9월>일,12월>일                      ← 분기
--   ***이어진 같은 묶음끼리 합쳐진다*** — DAY_ITEM 의 열 묶음과 같은 규칙이다.
--
-- ★행 그룹(`GRP_NM`)은 그대로 쓴다. 이 축의 서식은 대부분 행 묶음이 있다
--   (마약류/고위험약물/… · 위생환경관리/개인위생/… · 소방설비/경보설비/…).
--
-- ★셀 저장은 그대로 (행,열,값) — ROW=항목SORT, COL=열번호(1~N). ***DDL 은 칸 하나뿐이다.***
-- ═══════════════════════════════════════════════════════════════════════════

ALTER TABLE TBL_QPS_CHK_FORM
  ADD COLUMN COL_NMS VARCHAR(600) NULL
      COMMENT 'ITEM_COL 의 고정 열 이름(쉼표). 묶음은 묶음>열. 예 Y,N,비고 / 점검 및 조치>점검결과,점검 및 조치>조치 사항'
      AFTER HEAD_NMS;

-- ── 확인 ────────────────────────────────────────────────────────────────────
SELECT COLUMN_NAME, COLUMN_TYPE FROM INFORMATION_SCHEMA.COLUMNS
 WHERE TABLE_SCHEMA='WNN' AND TABLE_NAME='TBL_QPS_CHK_FORM'
   AND COLUMN_NAME IN ('HEAD_NMS','COL_NMS','AXIS_GB')
 ORDER BY ORDINAL_POSITION;
