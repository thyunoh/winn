--    ⇒ 판단 기준으로는 **여전히 1종**이라 축을 만들 이득이 없다(3종부터).
--      ***같은 모양(자유행 × 12월)이 2종 더 나오면 그때 `EQUIP_MONTH` 를 만든다.***
