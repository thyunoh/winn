--      ⇒ GUIDE_TXT 를 넓힌 뒤 등록한다(QPS_DDL_CHK_HALF_2026-08-12.sql 에 함께 둘 것).
--    ⚠정할 것 : 값이 O/X 가 아니라 **「유 / 무」** 다. 정규화는 안 건드리니 저장은 되지만
--      추출의 이행 요약(O/X 건수)에서 전부 '기타'로 빠진다. 병원이 알고 싶은 것은
