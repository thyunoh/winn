-- 점검표 엔진 v3 — 인쇄 배치 일반화 : 「반으로」가 아니라 **「N칸씩 + 방향」** (2026-08-12)
--
-- ★★이 파일은 **새 WAR 를 올리기 전에** 실행한다. (더하기만 하는 ALTER)
--
-- ★왜 — ***`HALF_YN` 은 「1~15 / 16~31」 하나만 할 수 있었다.*** 실물은 넷이다 :
--   | 실물 | 끊는 단위 | 방향 |
--   |---|---|---|
--   | 카트및엘리베이터 · 세탁물 보관소 · 소화전 · 육안일일 · 자동/반자동 조제기 · 세탁물보관실 | **15칸** | 열을 끊어 **위아래** |
--   | U.P.S 점검 일지 (시설) | **6칸**(1~6월 / 7~12월) | 열을 끊어 위아래 |
--   | **욕창예방활동 Checklist** (간호) | **7칸**(7일씩 **5쪽**) | 열을 끊어 위아래 |
--   | 의료가스 및 진공설비 · 비상발전기 주 점검 · 향정 비치 의약품 | 절반 | 행을 끊어 **좌우** |
--
--   ⇒ ***「반으로」가 아니라 「N칸씩」이고, 「위아래」가 아니라 「방향」이다.***
--     끊는 수와 방향만 서식이 정하면 넷이 한 장치로 풀린다.
--
-- ★값
--     SPLIT_N   : 몇 칸(행)씩 끊나. 0·NULL 이면 안 끊는다.
--     SPLIT_DIR : 'C' 열을 끊어 **위아래**로 / 'R' 행을 끊어 **좌우**로
--
-- ★***자투리가 1칸이면 앞 조각에 붙인다*** (2026-08-12 검증에서 나온 규칙)
--   31일을 15칸씩 끊으면 15·15·**1** 이라 1칸짜리 종이가 한 장 더 나온다 — 어떤 서식에서도 쓸모없다.
--   붙이면 `1~15 / 16~31` 로 **옛 HALF_YN 과 똑같아진다.**
--   7칸씩은 자투리가 3칸이라 그대로 둔다 ⇒ 욕창예방 **5쪽**이 맞다.
--   ⚠구현이 두 곳이다 — 작성 `qpsChk.jsp:splitRanges()` · 관리 `qpsChkForm.jsp:splitParts()`.
--     미리보기의 「몇 조각」과 종이가 갈리면 적는 사람이 숫자를 못 믿는다. 고칠 땐 둘 다.
--
-- ★기존 `HALF_YN` 은 지운다 —
--   ⚠**지금 지우지 않는다.** 12종이 전부 'N' 이라 실제 자료는 없지만, 컬럼을 지우면
--     옛 WAR 가 도는 동안 INSERT 가 깨진다(운영은 아직 옛 코드다).
--   ⇒ 컬럼은 남기고 **읽는 쪽에서만 물러난다** : `SPLIT_N` 이 비어 있고 `HALF_YN='Y'` 면
--     「15칸씩 · 열 · 위아래」로 읽는다. 나중에 운영까지 새 WAR 가 올라간 뒤 지운다.
-- ═══════════════════════════════════════════════════════════════════════════

ALTER TABLE TBL_QPS_CHK_FORM
  ADD COLUMN SPLIT_N INT NULL
      COMMENT '인쇄를 몇 칸(행)씩 끊나. 0·NULL=안 끊음 (종전 HALF_YN=Y 는 15와 같다)'
      AFTER HALF_YN,
  ADD COLUMN SPLIT_DIR CHAR(1) NULL
      COMMENT "끊는 방향 C=열을 끊어 위아래 / R=행을 끊어 좌우"
      AFTER SPLIT_N;

-- ── 확인 ────────────────────────────────────────────────────────────────────
SELECT COLUMN_NAME, COLUMN_TYPE FROM INFORMATION_SCHEMA.COLUMNS
 WHERE TABLE_SCHEMA='WNN' AND TABLE_NAME='TBL_QPS_CHK_FORM'
   AND COLUMN_NAME IN ('HALF_YN','SPLIT_N','SPLIT_DIR')
 ORDER BY ORDINAL_POSITION;
SELECT HALF_YN, SPLIT_N, SPLIT_DIR, COUNT(*) AS cnt
  FROM TBL_QPS_CHK_FORM GROUP BY HALF_YN, SPLIT_N, SPLIT_DIR;
