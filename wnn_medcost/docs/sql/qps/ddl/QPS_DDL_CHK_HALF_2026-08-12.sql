-- 점검표 엔진 v2 — 반달 접기 플래그 (2026-08-12)
--
-- ★★이 파일은 **새 WAR 를 올리기 전에** 실행해야 한다.
--   새 코드의 서식 조회가 HALF_YN 을 읽으므로, 컬럼이 없으면
--   「Unknown column 'HALF_YN'」 로 **서식 화면이 통째로 죽는다.**
--   순서 : ① 이 SQL  ② WAR 교체  ③ 톰캣 재기동
--
-- ★왜 컬럼을 더하나 — 기존 것을 돌려쓰지 않는 이유
--   PRD_GB('M'월/'Y'연)에 'H' 를 하나 더 넣으면 DDL 없이 되긴 한다. 하지만 그러면
--   **주기(언제 쓰나)와 인쇄 모양(어떻게 찍나)이 한 칸에 섞인다.**
--   부서(누가 쓰나)와 분류(무엇을 점검하나)를 굳이 갈라 둔 것과 같은 이유로 섞지 않는다.
--   ⇒ 뜻이 다른 것은 칸을 나눈다. 더하기만 하는 ALTER 라 기존 자료는 건드리지 않는다.
--
-- ★반달 접기란
--   1~31일이 가로로 뻗는 서식을 **인쇄할 때만** 1~15 / 16~31 두 블록으로 나눠 찍는다.
--   원본이 그렇게 생긴 것이 있다(카트및엘리베이터 청소소독 · 세탁물 보관소 청소 점검표).
--   ***화면은 한 표 그대로다*** — 편집은 한 표가 편하고, 종이만 원본을 따라간다.
--
-- ⚠일이 **열**인 축에서만 뜻이 있다(ITEM_DAY · EQUIP_DAY).
--   DAY_ITEM 은 일이 행이라 세로로 이미 나뉘고, ITEM_MONTH 는 12칸뿐이라 나눌 것이 없다.
-- ═══════════════════════════════════════════════════════════════════════════

-- ── 반달 접기 플래그 ────────────────────────────────────────────────────────
-- ★두 번 돌려도 안전하게 : 이미 있으면 Duplicate column name 으로 실패하니 확인 후 실행.
--   (MySQL 8.0 은 ADD COLUMN IF NOT EXISTS 를 지원하지 않는다 — MariaDB 만 된다.)
--   있는지 먼저 보려면 :
--     SELECT COLUMN_NAME FROM INFORMATION_SCHEMA.COLUMNS
--      WHERE TABLE_SCHEMA='WNN' AND TABLE_NAME='TBL_QPS_CHK_FORM' AND COLUMN_NAME='HALF_YN';

ALTER TABLE TBL_QPS_CHK_FORM
  ADD COLUMN HALF_YN CHAR(1) NOT NULL DEFAULT 'N'
      COMMENT '반달 접기 — 인쇄를 1~15 / 16~31 두 블록으로 (ITEM_DAY·EQUIP_DAY 만)'
      AFTER EQUIP_CNT;

-- ── 확인 ────────────────────────────────────────────────────────────────────
-- 기존 서식은 전부 'N' 이라 인쇄 모양이 그대로다(바뀌는 서식이 없다).
SELECT HALF_YN, COUNT(*) AS cnt FROM TBL_QPS_CHK_FORM GROUP BY HALF_YN;
