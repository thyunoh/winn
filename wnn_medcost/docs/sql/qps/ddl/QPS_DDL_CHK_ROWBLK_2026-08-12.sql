-- 점검표 엔진 v3 — **행 블록** : 한 문서에 표가 여럿, ***열은 같다*** (2026-08-12)
--
-- ★★이 파일은 **새 WAR 를 올리기 전에** 실행한다. (더하기만 하는 ALTER)
--
-- ★근거 6종 — 전부 「열은 같고 블록만 다르다」
--   | 서식 | 부서 | 블록 |
--   |---|---|---|
--   | 건강관리 현황표      | 영양 | 병원 근무자 17 / 배송기사 3 / 대체인력 3 |
--   | MSDS보관소 점검표    | 영양·시설 | spill kit 품목 8 / 보관소 내부 품목 6 |
--   | 유해화학물질 목록점검 | 시설 | 물질 구분별 |
--   | 공기조화설비(혼합형)  | 시설 | 설비 구분별 |
--   | 시설물 정기점검 2종   | 시설 | 일반 / 약국 / 조리실 … |
--   | 세탁물 관리          | 시설 | 구역별 |
--
-- ★★그런데 ***여섯이 둘로 갈린다.*** 여기가 이 작업의 전부다.
--
--   ⓐ **항목이 행인 축**(`ITEM_COL`·`ITEM_DAY`·`ITEM_MONTH`) — 시설 4종
--      블록 이름이 **이미 `TBL_QPS_CHK_ITEM.GRP_NM` 에 있다.** v2 의 「행 그룹」이 그것이다.
--      ⇒ ***저장할 것이 없다. 그리는 방법만 다르다*** —
--        지금은 **왼쪽 세로 칸**(rowspan)인데 원본은 **가로 띠**(표 폭을 가로지르는 머리 행)다.
--        ⇒ `ROW_BLK_GB` 한 칸이면 끝난다.
--
--   ⓑ **`LIST`**(행이 자유) — 영양 2종
--      행이 사람·품목이라 **블록 이름을 담을 곳이 없다**(항목은 열이다).
--      ⇒ ***서식이 블록을 정한다*** : `ROW_BLKS = '병원 근무자>17,배송기사>3,대체인력>3'`
--        (`COL_NMS` 의 `묶음>열` 과 **같은 문법** — 사람이 새로 배울 것이 없다.)
--        `>뒤 숫자`는 **처음에 깔아 줄 행 수**다. 모자라면 블록마다 「＋행 추가」로 늘린다.
--
-- ★★행 번호를 블록마다 **1000 단위로 띄운다** — `블록 b 의 i 번째 행 = b*1000 + i`
--   ⚠***붙여서 매기면 안 된다.*** 1블록이 17행이라 2블록을 18부터 매기면,
--     병원이 1블록에 한 사람을 더하는 순간 **2블록 전체가 한 칸씩 밀려** 지난달 자료가 어긋난다.
--     띄워 두면 블록끼리 영향이 없다. (999행이면 어떤 대장도 넘치지 않는다.)
--   · `SIGN_NO=900`(점검자 사인 행)과 겹치지 않는다 — 블록은 1001 부터다.
--   · ***읽을 때 `ROW_NO < 1000` 은 블록 1 로 본다*** — 블록 없이 쓰던 서식에 나중에
--     블록을 붙여도 옛 문서가 살아 있게.
--
-- ★값
--     ROW_BLK_GB : 행 묶음을 어떻게 그리나. NULL·'S' = 왼쪽 세로 칸(지금) / 'B' = **가로 띠**
--                  ⇒ 항목이 행인 축에만 뜻이 있다. `LIST` 는 블록이 있으면 언제나 띠다.
--     ROW_BLKS   : `LIST` 전용. `블록명>기본행수,블록명>기본행수`. 비면 블록 없음(지금 그대로).
-- ═══════════════════════════════════════════════════════════════════════════

ALTER TABLE TBL_QPS_CHK_FORM
  ADD COLUMN ROW_BLK_GB CHAR(1) NULL
      COMMENT "행 묶음 표시 S=왼쪽 세로 칸(기본) / B=가로 띠. 항목이 행인 축만"
      AFTER COL_NMS,
  ADD COLUMN ROW_BLKS VARCHAR(600) NULL
      COMMENT "LIST 전용 행 블록 '이름>기본행수,이름>기본행수'. 행번호는 블록마다 1000 단위"
      AFTER ROW_BLK_GB;

-- ── 확인 ────────────────────────────────────────────────────────────────────
SELECT COLUMN_NAME, COLUMN_TYPE, COLUMN_COMMENT FROM INFORMATION_SCHEMA.COLUMNS
 WHERE TABLE_SCHEMA='WNN' AND TABLE_NAME='TBL_QPS_CHK_FORM'
   AND COLUMN_NAME IN ('COL_NMS','ROW_BLK_GB','ROW_BLKS')
 ORDER BY ORDINAL_POSITION;
SELECT AXIS_GB, IFNULL(ROW_BLK_GB,'-') AS ROW_BLK_GB, IFNULL(ROW_BLKS,'-') AS ROW_BLKS, COUNT(*) AS cnt
  FROM TBL_QPS_CHK_FORM GROUP BY AXIS_GB, ROW_BLK_GB, ROW_BLKS ORDER BY AXIS_GB;
