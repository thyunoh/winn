-- 점검표 엔진 — **주기 복합** : 행 묶음마다 기간 축이 다른 격자 (2026-08-14)
--
-- ★★이 파일은 **새 JSP·매퍼를 올리기 전에** 실행한다. (더하기만 하는 ALTER)
--   옛 코드는 이 칸을 읽지도 쓰지도 않는다 ⇒ 운영 선적용이 안전하다(08-12·08-13·08-14 와 같은 판단).
--
-- ★근거 10종 — 진단검사(임상병리) 기기 점검표. 판독 : docs/proposals/QPS_서식판독_진단검사_2026-08-14.md
--   8 롤믹스기 · 13 원심분리기 · 15 현미경 · 16 소변분석기 · 17 HGB A1C ·
--   18 혈액가스 · 19 생화학 · 20 혈액학 · 21 전해질 · 36 공통판
--
--   담아야 할 모양 — ***한 장짜리 종이인데 격자가 세로로 3벌이고 기간 축이 서로 다르다*** :
--     매일  점검항목 7행 × 1~31일
--     매주  점검항목 5행 × 1주~5주   (+ 주마다 날짜 적는 줄)
--     매월  점검항목 4행 × [한 칸]
--     ─────────────────────────
--     점검자 확인란 31칸 · 수리날짜 및 고장 발생 내용
--
-- ★★왜 새 칸이 필요한가 — 있는 것으로는 안 된다
--   · `PRD_KIND`  : 기간 종류가 **서식에 하나**다. 여기는 묶음마다 다르다.
--   · `PRD_SUB`   : 「한 기간 칸을 쪼개는」 장치다(1일을 오전/오후로). 여기는 **기간 축 자체가 다르다**.
--   · `ROW_BLKS`  : ***LIST 전용***이고 행번호를 블록×1000 으로 띄우는 규칙이다. 뜻이 다르다.
--   · 블록 반복   : **같은 격자가 N벌**이다(근무조 D/E/N). 여기는 **서로 다른 격자 3벌**.
--   · 서식 3개로 쪼개기 : 한 장짜리 종이다 — 인쇄가 3장으로 갈리고 점검자 확인란이 셋이 된다.
--
-- ★★그래서 **묶음(GRP_NM) 에 기간 축을 붙인다** — 새 축도 새 표도 만들지 않는다.
--   묶음 이름은 ***이미 `TBL_QPS_CHK_ITEM.GRP_NM` 에 있다***(v2 의 「행 그룹」).
--   없던 것은 「그 묶음이 어떤 기간으로 뻗는가」 하나뿐이다.
--
--   GRP_PRD = '매일>D,매주>N,매월>1'      묶음이름 > 기간축
--     ⇒ `COL_NMS` 의 `묶음>열`, `ROW_BLKS` 의 `이름>행수` 와 **같은 문법**이라 새로 배울 것이 없다.
--
--   기간축 값은 ***`PRD_KIND` 와 같은 글자를 쓴다*** — 두 곳에서 다른 뜻이면 반드시 헷갈린다.
--     D 일(1~그달 날수) · W 요일(7) · N 주차(5) · M 월(12) · Q 분기(4)
--     **1** = 한 칸 (그 달 전체가 칸 하나) ← 이번에 새로 생긴 값. 「매월」 구간이 이것이다.
--
-- ★비면 지금과 똑같이 동작한다 — 서식 하나의 `PRD_KIND` 로 격자 한 벌을 그린다.
--   ***기존 서식 177종은 하나도 안 바뀐다.***
--
-- ★값 자리는 손대지 않는다 (`TBL_QPS_CHK_VAL` 그대로)
--   항목(행)이 이미 묶음별로 다르므로 **행번호가 곧 묶음을 가른다.**
--   열번호의 뜻은 그 행이 속한 묶음의 기간축이 정한다(매일 3열=3일 · 매주 3열=3주차).
--   ⇒ 9000대(자유행 표)·1000단위(LIST 블록)·890(기간머리)·900(사인) 예약대와 안 겹친다.
-- ═══════════════════════════════════════════════════════════════════════════

ALTER TABLE TBL_QPS_CHK_FORM
  ADD COLUMN GRP_PRD VARCHAR(300) NULL
      COMMENT "주기 복합 '묶음명>기간축,…' 축=D일 W요일 N주차 M월 Q분기 1한칸. 비면 서식 PRD_KIND 하나"
      AFTER PRD_SUB;

-- ── 확인 ────────────────────────────────────────────────────────────────────
SELECT COLUMN_NAME, COLUMN_TYPE, IS_NULLABLE, COLUMN_COMMENT
  FROM INFORMATION_SCHEMA.COLUMNS
 WHERE TABLE_SCHEMA='WNN' AND TABLE_NAME='TBL_QPS_CHK_FORM'
   AND COLUMN_NAME IN ('PRD_KIND','PRD_SUB','GRP_PRD')
 ORDER BY ORDINAL_POSITION;

-- 지금은 아무 서식도 안 쓴다(전부 NULL) — 시드를 넣기 전 상태 확인용
SELECT COUNT(*) AS all_form, COUNT(GRP_PRD) AS grpprd_set FROM TBL_QPS_CHK_FORM;
