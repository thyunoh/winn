-- 점검표 엔진 v3 — 격자의 「기간 칸 종류」를 서식이 정한다 (2026-08-12)
--
-- ★★이 파일은 **새 WAR 를 올리기 전에** 실행한다. (더하기만 하는 ALTER — 기존 서식은 안 바뀐다)
--
-- ★왜 — ***날짜 격자가 「1~31일」과 「1~12월」 둘뿐이었다.*** 실물에는 더 있다 :
--   | 기간 칸 | 종수 | 근거 실물 |
--   |---|---|---|
--   | 요일 7칸(월~일) | **4** | 식중독 예방 위생 점검 일지 · 냉장고/냉동고/주방 온도습도 · 온도 관리 기록지 · 병동 위생관리 계획표 |
--   | 주차 5칸(1~5주) | **7** | CCTV · 가스보일러 · 전기시설주간 · 세탁물관리 · 세탁물집하장 운반용기 · 병동 환경 위생 · 응급약품 및 기구관리 |
--   | 분기 4칸        | 1 | 건축물 안전 점검 일지 — ***ITEM_COL 로 이미 풀린다*** |
--
-- ★★축 이름을 늘리지 않는다 — **(방향) × (기간 종류)** 로 푼다.
--   축은 「항목이 행이냐 열이냐」만 말하고, 기간 칸이 무엇인지는 이 칸이 말한다.
--     ITEM_DAY + PRD_KIND='W'  → 점검항목 행 × 월~일 7칸        (식중독 예방)
--     DAY_ITEM + PRD_KIND='W'  → 요일 행 × 점검항목 열          (온도 관리 기록지)
--     ITEM_DAY + PRD_KIND='N'  → 점검항목 행 × 1~5주차          (CCTV)
--     DAY_ITEM + PRD_KIND='M'  → **1~12월 행 × 항목 열**        (냉·난방 필터 청소 점검일지)
--   ***★마지막 줄이 핵심이다*** — 종전에 `MONTH_ITEM` 이라는 새 축이 필요해 보였던 것이
--   조합으로 저절로 나온다. **축 짝의 빈자리가 이렇게 채워진다.**
--
-- ★값 : D 일(1~그달 날수) · W 요일(월~일 7) · N 주차(1~5) · M 월(1~12) · Q 분기(1~4)
--   ⚠**비어 있으면 축에서 유추한다** — ITEM_MONTH → 'M', 그 외 → 'D'.
--     그래서 기존 서식 12종은 값을 안 넣어도 지금과 똑같이 그려진다.
--
-- ★문서 단위(PRD_GB)와 다른 것이다. 헷갈리지 말 것 :
--     PRD_GB   = 이 문서가 **얼마 동안**의 것인가(연·반기·분기·월·주·일) — TBL_QPS_CHK_DOC
--     PRD_KIND = 격자의 **기간 칸이 무엇**인가(일·요일·주차·월·분기) — TBL_QPS_CHK_FORM
--   예) 「식중독 예방 위생 점검 일지」는 문서가 **주 1장**(PRD_GB='W')이고 격자는 **요일 7칸**(PRD_KIND='W').
--       「CCTV 점검표」는 문서가 **월 1장**(PRD_GB='M')이고 격자는 **주차 5칸**(PRD_KIND='N').
-- ═══════════════════════════════════════════════════════════════════════════

ALTER TABLE TBL_QPS_CHK_FORM
  ADD COLUMN PRD_KIND CHAR(1) NULL
      COMMENT '격자 기간 칸 D일 W요일 N주차 M월 Q분기 — 비면 축에서 유추(ITEM_MONTH=M, 그 외 D)'
      AFTER PRD_GB;

-- ── 확인 ────────────────────────────────────────────────────────────────────
SELECT COLUMN_NAME, COLUMN_TYPE FROM INFORMATION_SCHEMA.COLUMNS
 WHERE TABLE_SCHEMA='WNN' AND TABLE_NAME='TBL_QPS_CHK_FORM'
   AND COLUMN_NAME IN ('AXIS_GB','PRD_GB','PRD_KIND','COL_NMS')
 ORDER BY ORDINAL_POSITION;
SELECT AXIS_GB, PRD_GB, PRD_KIND, COUNT(*) AS cnt
  FROM TBL_QPS_CHK_FORM GROUP BY AXIS_GB, PRD_GB, PRD_KIND ORDER BY AXIS_GB;
