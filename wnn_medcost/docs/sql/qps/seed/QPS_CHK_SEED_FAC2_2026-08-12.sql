SELECT f.FORM_ID, f.AXIS_GB, f.PRD_GB, IFNULL(f.PRD_KIND,'-') AS kind, COUNT(i.SORT) AS items,
       SUM(CASE WHEN i.SPAN_TXT IS NOT NULL THEN 1 ELSE 0 END) AS spans,
       SUM(CASE WHEN i.BLK_NM  IS NOT NULL THEN 1 ELSE 0 END) AS blks,
       SUM(CASE WHEN i.CARRY_YN='Y' THEN 1 ELSE 0 END)        AS carry
  FROM TBL_QPS_CHK_FORM f LEFT JOIN TBL_QPS_CHK_ITEM i
    ON i.FORM_ID=f.FORM_ID AND i.HOSP_CD=f.HOSP_CD
 WHERE f.HOSP_CD='*' AND f.FORM_ID IN
 ('FAC023','FAC024','FAC025','FAC027','FAC028','FAC029','FAC030','FAC031','FAC032','FAC033',
  'FAC035','FAC036','FAC037','FAC038','FAC039','FAC040','FAC041','FAC042','FAC043','FAC044',
